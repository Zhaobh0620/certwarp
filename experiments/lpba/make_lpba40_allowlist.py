"""LP-A (runs/20261119-lpba/任务书_A_数据准入HI与Atropos.md item 1; contract C26.3-5; LPBA40 prereg §8.5 item 3, §12 item 6): the LPBA entries' own allowlist,
configs/bayesreg/lpba40_test_v1_allowlist.json -- written once by this generator, then pinned in bayesreg.io.guard (LPBA40_ALLOWLIST_REL, LPBA40_ALLOWLIST_SHA256).

Content (C26.3-5, word for word): every source of the development allowlist configs/bayesreg/dev_subjects.json, copied item by item (bayesreg_train_v1 with the 106
label_contact_subjects of the v4 members, stage_LPBA40_v1_tune with S01-S24, ...), plus the new source lpba40_test_v1: dataset LPBA40, the 34 subjects of
splits/lpba40_test_v1/test_subjects.txt (S03-S36), path that file, sha256 that file's; never_for_training false (D143, decision_log line 531).  subjects per dataset = the
union of the sources (guard._parse_allowlist).  The document is written with json.dumps(indent=1, ensure_ascii=False) and a final newline, the form of dev_subjects.json.
Only added, never changed (C26.3-5): another content is a new file and a new pin.  This reads the two code-tree files only (no subject file, no data root).

    python -B experiments/lpba/make_lpba40_allowlist.py --check     the committed file equals the document (exit 0) or not (exit 1)
    python -B experiments/lpba/make_lpba40_allowlist.py --write     writes the file when it is absent (never overwrites)
"""
import argparse
import hashlib
import json
from pathlib import Path
import sys

REPO = Path(__file__).resolve().parents[2]
DEV_ALLOWLIST_REL = 'configs/bayesreg/dev_subjects.json'
OUT_REL = 'configs/bayesreg/lpba40_test_v1_allowlist.json'           # = bayesreg.io.guard.LPBA40_ALLOWLIST_REL (a test compares)
TEST_SUBJECTS_REL = 'splits/lpba40_test_v1/test_subjects.txt'
TEST_SUBJECTS_SHA256 = '161f379290b6d3b0e52118570d9bc23e14197e34e77e5263c87f22a84fd5deb9'    # splits/lpba40_test_v1/SHA256SUMS line 3
SOURCE = 'lpba40_test_v1'
COMMENT = ('LPBA40 second test set: the LPBA entries\' own allowlist (contract C26.3-5; LPBA40 prereg section 8.5 item 3), generated by '
           'experiments/lpba/make_lpba40_allowlist.py: every source of configs/bayesreg/dev_subjects.json copied item by item, plus the source '
           'lpba40_test_v1 (S03-S36 of splits/lpba40_test_v1/test_subjects.txt; never_for_training false, D143). Loaded only by the LPBA entries by '
           'its pinned path and sha256 (bayesreg.io.guard.LPBA40_ALLOWLIST_REL, LPBA40_ALLOWLIST_SHA256); only added, never changed.')


def sha256_bytes(raw):
    return hashlib.sha256(raw).hexdigest()


def document(repo=REPO):
    dev_raw = (Path(repo)/DEV_ALLOWLIST_REL).read_bytes()
    dev = json.loads(dev_raw.decode('utf-8'))
    test_raw = (Path(repo)/TEST_SUBJECTS_REL).read_bytes()
    if sha256_bytes(test_raw) != TEST_SUBJECTS_SHA256:
        raise SystemExit(f'{TEST_SUBJECTS_REL}: sha256 {sha256_bytes(test_raw)} is not the pinned {TEST_SUBJECTS_SHA256}')
    test = [line for line in test_raw.decode('utf-8').splitlines() if line.strip()]
    if test != [f'S{n:02d}' for n in range(3, 37)]:
        raise SystemExit(f'{TEST_SUBJECTS_REL}: not S03-S36 in order')
    if any(s['name'] == SOURCE for s in dev['sources']):
        raise SystemExit(f'{DEV_ALLOWLIST_REL} already has a source {SOURCE!r}')
    sources = [dict(s) for s in dev['sources']]+[dict(name=SOURCE, dataset='LPBA40', path=TEST_SUBJECTS_REL, sha256=TEST_SUBJECTS_SHA256,
                                                      never_for_training=False, subjects=test)]
    subjects = {}
    for source in sources:
        held = subjects.setdefault(source['dataset'], [])
        held += [s for s in source['subjects'] if s not in held]
    subjects = {dataset: sorted(ids) for dataset, ids in sorted(subjects.items())}
    return dict(schema=dev['schema'], comment=COMMENT, subjects=subjects, sources=sources)


def text(repo=REPO):
    return json.dumps(document(repo), indent=1, ensure_ascii=False)+'\n'


def main(argv=None):
    ap = argparse.ArgumentParser()
    group = ap.add_mutually_exclusive_group(required=True)
    group.add_argument('--check', action='store_true')
    group.add_argument('--write', action='store_true')
    a = ap.parse_args(argv)
    out = REPO/OUT_REL
    want = text().encode('utf-8')
    if a.write:
        if out.exists():
            print(f'{out} exists: never overwritten')
            return 1
        out.write_bytes(want)
        print(f'{OUT_REL}: written, sha256 {sha256_bytes(want)}')
        return 0
    same = out.is_file() and out.read_bytes() == want
    print(f'{OUT_REL}: {"equal to" if same else "NOT equal to"} the generated document (sha256 {sha256_bytes(want)})')
    return 0 if same else 1


if __name__ == '__main__':
    sys.exit(main())
