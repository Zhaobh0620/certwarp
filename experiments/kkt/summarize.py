"""Collect kkt_v1/<label>.json into summary.json and summary.md (tables for runs/20261031-kkt/result.md)."""
import json
from pathlib import Path

ROOT = Path("/home/rmcfz/seq_vp_tag_results/kkt_v1")
LABELS = ["R1-k500", "R1-k1000", "R1-k2000", "R1-final", "R5-final", "R3-final", "R7-k1000", "R7-final"]


def g(x, fmt=".3g"):
    return "—" if x is None else format(x, fmt)


def main():
    docs = {lab: json.loads((ROOT/f"{lab}.json").read_text()) for lab in LABELS}
    lines = ["# KKT summary (generated by experiments/kkt/summarize.py)", ""]
    lines += ["## 1. NNLS, pre-registered selection b_K < t (Euclidean, single-point cone)", "",
              "| state | k | GF_B | T_B | cert min b_K | true min J | t | cells | r/GF_B | r/T_B | explained | -g explained |"
              " support bound | multi-point explained | M^-1 r/‖g‖ | λ>0 |",
              "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    out = {}
    for lab, d in docs.items():
        bs = d["blind_spot"].get("0.1") or {}
        true_min = bs.get("J_dense", {}).get("min") if bs else None
        rec = dict(GF_B=d["check"]["GF_B"], T_B=d["T_B"], cert_min=d["certificate"]["min_jd_lower_bound"],
                   true_min_J=true_min, nnls={}, posthoc={})
        for t in ("0.01", "0.001", "0.0001", "0.1", "0.25"):
            e = d["nnls"][t]
            rec["nnls"][t] = {k: e.get(k) for k in ("n_cells", "r_over_GF", "r_over_T_B", "explained_share",
                                                     "minus_g_explained_share", "support_upper_bound_share")}
            rec["nnls"][t]["multi_point"] = e.get("multi_point", {}).get("explained_share")
            rec["nnls"][t]["M_r"] = e.get("M_inverse_norm", {}).get("r_over_gnorm")
            rec["nnls"][t]["n_lambda"] = e.get("lambda", {}).get("n_nonzero")
            lines.append(f"| {lab} | {d['k']} | {d['check']['GF_B']:.4g} | {d['T_B']:.3g} | "
                         f"{d['certificate']['min_jd_lower_bound']:.2g} | {g(true_min, '.3g')} | {t} | {e['n_cells']} | "
                         f"{e['r_over_GF']:.4f} | {g(e.get('r_over_T_B'), '.3g')} | {e['explained_share']:.4f} | "
                         f"{g(e.get('minus_g_explained_share'), '.4f')} | {g(e.get('support_upper_bound_share'), '.3f')} | "
                         f"{g(rec['nnls'][t]['multi_point'], '.3f')} | {g(rec['nnls'][t]['M_r'], '.4f')} | "
                         f"{g(rec['nnls'][t]['n_lambda'], 'd')} |")
        for t, e in d["nnls_true_J_posthoc"].items():
            rec["posthoc"][t] = {k: e.get(k) for k in ("n_cells", "r_over_GF", "explained_share",
                                                        "minus_g_explained_share", "support_upper_bound_share")}
            rec["posthoc"][t]["multi_point"] = e.get("multi_point", {}).get("explained_share")
        out[lab] = rec
    lines += ["", "## 2. Post hoc: near-active by the dense minimum J_dense < t (not pre-registered)", "",
              "| state | t | cells | r/GF_B | explained | -g explained | support bound | multi-point explained |",
              "|---|---|---|---|---|---|---|---|"]
    for lab, d in docs.items():
        for t, e in d["nnls_true_J_posthoc"].items():
            lines.append(f"| {lab} | {t} | {e['n_cells']} | {e['r_over_GF']:.4f} | {e['explained_share']:.4f} | "
                         f"{g(e.get('minus_g_explained_share'), '.4f')} | {g(e.get('support_upper_bound_share'), '.3f')} | "
                         f"{g(e.get('multi_point', {}).get('explained_share'), '.3f')} |")
    lines += ["", "## 3. F_B blocks (absolute; per brain node; per brain cell)", ""]
    for lab, d in docs.items():
        en = d["energy"]
        nb, nc = d["counts"]["brain_nodes"], d["counts"]["brain_cells"]
        lines.append(f"### {lab}: F_B = {en['F_B']:.7g}, data = {en['data_total']:.7g}; brain nodes {nb}, brain cells {nc}")
        lines.append("")
        lines.append("| block | F | per brain node | per brain cell | share of F_B |")
        lines.append("|---|---|---|---|---|")
        for k, v in en["blocks"].items():
            lines.append(f"| {k} | {v:.6g} | {en['per_brain_node'][k]:.4g} | {en['per_brain_cell'][k]:.4g} | "
                         f"{v/en['F_B']:.4f} |")
        lines.append("")
        out[lab]["energy"] = en
    lines += ["## 4. Quadrature blind spot (cells with b_K < t)", "",
              "| state | t | n | J53 min / median | J_dense min / median | b_K min / median | J53/J_dense max |"
              " b_K/J_dense median | #J53 > 2 J_dense | argmin location |", "|---|---|---|---|---|---|---|---|---|---|"]
    for lab, d in docs.items():
        for t in ("0.1", "0.01", "0.001"):
            b = d["blind_spot"].get(t)
            if not b:
                continue
            lines.append(f"| {lab} | {t} | {b['n']} | {b['J53']['min']:.3g} / {b['J53']['median']:.3g} | "
                         f"{b['J_dense']['min']:.3g} / {b['J_dense']['median']:.3g} | {b['b_K']['min']:.2g} / "
                         f"{b['b_K']['median']:.2g} | {b['ratio_J53_over_dense']['max']:.4f} | "
                         f"{b['ratio_bK_over_dense']['median']:.3g} | {b['n_J53_gt_2x_dense']} | "
                         f"{b['argmin_location']} |")
            out[lab].setdefault("blind_spot", {})[t] = {k: v for k, v in b.items() if k != "cells"}
    lines += ["", "## 5. JD-scaling factor classes (share of ||g||^2 on the nodes)", "",
              "| state | class | nodes | share of ‖g‖² |", "|---|---|---|---|"]
    for lab, d in docs.items():
        for k, v in d["jd_scaling_posthoc"]["classes"].items():
            lines.append(f"| {lab} | {k} | {v['nodes']} | {v['share_g2']:.4f} |")
        out[lab]["jd_classes"] = d["jd_scaling_posthoc"]["classes"]
    lines += ["", "## 6. Gradient blocks (GF normalization), whole field", "", "| state | channel | diffusion | logvol | curl | total |",
              "|---|---|---|---|---|---|"]
    for lab, d in docs.items():
        b = d["gradient_blocks_GF"]
        lines.append(f"| {lab} | {b['channel']:.4g} | {b['diffusion']:.3g} | {b['logvol']:.4g} | {b['curl']:.4g} | "
                     f"{d['check']['GF_B']:.4g} |")
    (ROOT/"summary.md").write_text("\n".join(lines)+"\n", encoding="utf-8")
    (ROOT/"summary.json").write_text(json.dumps(out, indent=1, default=float)+"\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
