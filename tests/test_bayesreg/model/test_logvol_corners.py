@pytest.mark.parametrize("spacing", [(1., 1., 1.), (.9, 1.1, 1.3)], ids=["isotropic", "anisotropic"])
def test_b3_2_counterexample_corners_undefined(spacing):
    """02_理论 B3(2) construction (C07 gate): every Gauss J_q > 0 (min .0683), legal sampling; with the default the
    F_B is finite; with "gauss27+corners" F_B is undefined: InvalidTrial NONPOSITIVE_GAUSS_JD whose count is the
    number of corners with J <= 0 (4 on K0's face xi_1 = 1, J = -.05 there), and stable_reduction refuses a state
    with a nonpositive corner J."""
    hx, hy, hz = spacing
    grid = make_grid_3d(nx=7, ny=7, nz=7, hx=hx, hy=hy, hz=hz, x0=-1., y0=.5, z0=-2., unit="mm")
    u = np.zeros(grid.shape+(3,))
    u[3, 2, 3, 2] = u[3, 3, 3, 2] = -1.05*hz
    state = make_state(grid, seed=11)
    geo = gauss_geometry(u, state.ops)
    assert geo.J.min() > 0 and abs(geo.J.min()-(1-1.05*(.5+np.sqrt(15)/10))) <= 1e-14
    assert check_map_domain(u, grid) is None
    ev = evaluate(state, u)
    assert isinstance(ev, Evaluation) and np.isfinite(ev.energy)
    corners = state.replace(logvol_points=CORNERS)
    J = gauss_geometry(u, corners.corner_ops).J
    k0 = int(np.ravel_multi_index((2, 2, 2), grid.cell_shape))
    np.testing.assert_allclose(J[k0], 1-1.05*corners.corner_ops.points[:, 0], rtol=0, atol=1e-14)
    n_bad = int(np.count_nonzero(J <= 0))
    assert n_bad >= 4 and np.all(J[k0][corners.corner_ops.points[:, 0] == 1] < 0)
    failure = evaluate(corners, u)
    assert isinstance(failure, InvalidTrial) and failure.reason == "NONPOSITIVE_GAUSS_JD"
    assert failure.invalid_count == n_bad and "corner" in failure.message
    bad = gauss_value(LogVolumeCorners, corners, u)
    assert isinstance(bad, InvalidTrial) and bad.invalid_count == n_bad
    forged = Evaluation(corners, ev.u, ev.channel, ev.total, ev.energy, ev.energies)    # never produced by evaluate
    with pytest.raises(InputValidationError, match="J <= 0"):
        stable_reduction(corners, evaluate(corners, np.zeros_like(u)), forged)


@pytest.mark.parametrize("beta_c", [1., 2.])
def test_affine_field_corner_term(beta_c, record_property):
    """C05 gate for C05-2a: on an affine map x + (A - I)(x - x0) every corner J equals det A and the corner term
    is (beta_c/2) sum_K sum_v omega/(8 omega0) (log det A)^2 / tau_{K,v}^2 (1e-13 relative); with tau constant it is
    (beta_c/2)(|K| omega/omega0)(log det A)^2/tau^2."""
    g = aniso()
    state = make_state(g, seed=4).replace(logvol_points=CORNERS, corner_weight=beta_c)
    Amat = np.array([[1.1, .05, -.02], [.03, .95, .04], [-.01, .02, 1.07]])
    X = g.identity()
    u = (X-X[0, 0, 0])@(Amat-np.eye(3)).T
    tile = slice(0, g.n_cells)
    geo = tile_geometry(node_field(u, g, allow_nonzero_faces=True), state.corner_ops, tile=tile)
    det = np.linalg.det(Amat)
    assert np.max(np.abs(geo.J-det)) <= 1e-14
    r = LogVolumeCorners.residual(LogVolumeCorners.scale(state, tile), geo)
    tau2 = LogVolumeCorners.tau2(state, tile)
    expected = .5*beta_c*np.sum(g.omega/(8*state.omega0)/tau2)*np.log(det)**2
    errors = dict(general=abs(.5*np.sum(r*r)-expected)/expected)
    flat = state.replace(tissue=np.full_like(state.tissue, 1/state.tissue.shape[0]))
    tau2_const = float(np.mean(flat.tau2))
    r = LogVolumeCorners.residual(LogVolumeCorners.scale(flat, tile), geo)
    expected = .5*beta_c*g.n_cells*g.omega/state.omega0*np.log(det)**2/tau2_const
    errors["constant_tau"] = abs(.5*np.sum(r*r)-expected)/expected
    record_property("affine_errors", json.dumps(errors))
    assert max(errors.values()) <= 1e-13, errors


