def _golden_constant(path, name="GOLDEN_481E33B"):
    """`name` = dict(...) of a test file (GOLDEN_481E33B, GOLDEN_DEF), read by ast (no import)."""
    import ast
    for node in ast.parse(path.read_text(encoding="utf-8")).body:
        if isinstance(node, ast.Assign) and [t.id for t in node.targets if isinstance(t, ast.Name)] == [name]:
            return {k.arg: ast.literal_eval(k.value) for k in node.value.keywords}
    raise AssertionError(f"{path}: no {name}")


