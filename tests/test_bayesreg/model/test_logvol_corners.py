    state, _ = D.small_case(**D.pre_def_model())
    digest = hashlib.sha256()
    for part in (state.grid.grid_id, repr(float(state.omega0)), repr(int(state.tile_size)), repr(float(state.alpha)),
                 repr(float(state.nu)), array_sha256(state.sigma2), array_sha256(state.tau2),
                 array_sha256(state.weights), array_sha256(state.fixed), array_sha256(state.mask),
                 array_sha256(state.tissue), *[s.image_id for s in state.samplers]):
        digest.update(part.encode())
        digest.update(b"|")
    assert model_identity(state) == digest.hexdigest()
    corners = state.replace(logvol_points=CORNERS)
    heavier = state.replace(logvol_points=CORNERS, corner_weight=2.)
