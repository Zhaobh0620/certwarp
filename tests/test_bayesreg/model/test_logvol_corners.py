def dense_corner_operators(grid):
    """D (3, 8|K|, N) physical shape derivatives, B (8|K|, N) shape values and w (8|K|,) = omega/8 at the cell
    corners (z, y, x product, x fastest; cells in C order), from the scalar Q1 formula (not CellQ1Operators3D)."""
    points = [(px, py, pz) for pz, py, px in product((0., 1.), repeat=3)]
    P, N = len(points), int(np.prod(grid.shape))
    D = np.zeros((3, grid.n_cells*P, N))
    B = np.zeros((grid.n_cells*P, N))
    for c, (cz, cy, cx) in enumerate(np.ndindex(grid.cell_shape)):
        for vz, vy, vx in product((0, 1), repeat=3):
            node = np.ravel_multi_index((cz+vz, cy+vy, cx+vx), grid.shape)
            vertex = (vx, vy, vz)
            for k, point in enumerate(points):
                row = c*P+k
                B[row, node] = np.prod([point[t] if vertex[t] else 1-point[t] for t in range(3)])
                for j in range(3):
                    value = (2*vertex[j]-1)/grid.spacing[j]
                    for t in range(3):
                        if t != j:
                            value *= point[t] if vertex[t] else 1-point[t]
                    D[j, row, node] = value
    return D, B, np.full(grid.n_cells*P, grid.omega/8)


def dense_corners(state, u):
    """(r, K) of the corner part of r_J: r = sqrt(beta_c omega/(8 omega0 tau^2)) log J at the corners, rows
    (cell, corner); K (8|K|, 3 N_int) explicit."""
    g = state.grid
    D, B, w = dense_corner_operators(g)
    S = selection(g)
    U = np.asarray(u).reshape(-1, 3)
    F = np.einsum("jqn,nr->qrj", D, U)+np.eye(3)
    A, J = cofactor(F), np.linalg.det(F)
    tau2 = sum(t*(B@state.tissue[k].ravel()) for k, t in enumerate(state.tau2))
    s = np.sqrt(state.corner_weight*w/(state.omega0*tau2))
    DS = [D[j]@S for j in range(3)]
    L = np.concatenate([sum(A[:, r, j, None]*DS[j] for j in range(3)) for r in range(3)], axis=1)
    return s*np.log(J), (s/J)[:, None]*L, J


