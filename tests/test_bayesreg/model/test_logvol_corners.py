def decimal_corner_change(state, base, trial):
    """1/2 sum_{K,v} w (ln J_t^2 - ln J_b^2) of the corner term, w = beta_c omega/(8 omega0 tau^2), 110 digits."""
    tile = slice(0, state.grid.n_cells)
    tau2 = LogVolumeCorners.tau2(state, tile)
    weights = np.broadcast_to(state.corner_weights, tau2.shape)
    ops = corners8(state.grid)
    J_b = tile_geometry(node_field(base.u, state.grid), ops, tile=tile).J
    J_t = tile_geometry(node_field(trial.u, state.grid), ops, tile=tile).J
    total = Decimal(0)
    for jb, jt, w, t2 in zip(J_b.ravel(), J_t.ravel(), weights.ravel(), tau2.ravel()):
        lb, lt = Decimal(float(jb)).ln(), Decimal(float(jt)).ln()
        total += Decimal(float(w))/(Decimal(state.omega0)*Decimal(float(t2)))*(lt-lb)*(lt+lb)/2
    return total


def test_stable_reduction_with_corners(record_property):
    """C08 with the corners: equal states give Delta E = 0 exactly; a generic step and a cancellation step
    (u_t - u_b ~ 1e-10 |u|) match 110-digit Decimal (corner term included) to 1e-15; the generic step agrees with the
    float64 difference within the guard; the log-volume block is the per-tile longdouble sum Gauss term then corner
    term (bitwise); a compared state with J <= 0 at a corner raises."""
    g, state, rng, u = corner_setup(seed=9, student_t=False)
    base = evaluate(state, u)
    direction = inject_free(free_random(g, rng), g)
    direction *= np.max(np.abs(u))/np.max(np.abs(direction))
    same = stable_reduction(state, base, evaluate(state, u.copy()))
    assert same.delta == 0 and same.ared == 0 and same.reason == "ENERGY_RESOLUTION"
    errors = {}
    with localcontext() as ctx:
        ctx.prec = 110
        for name, step in (("generic", .3), ("cancellation", 1e-10)):
            trial = evaluate(state, u+step*direction)
            red = stable_reduction(state, base, trial)
            reference = decimal_model_change(state, base, trial)+decimal_corner_change(state, base, trial)
            errors[name] = relative(red.delta, reference)
            if name == "generic":
                errors["generic_vs_float64"] = abs(red.ared-(base.energy-trial.energy))/red.guard
                generic = (trial, red)
    record_property("reduction_errors", json.dumps(errors))
    assert errors["generic"] <= 1e-15 and errors["cancellation"] <= 1e-15 and errors["generic_vs_float64"] <= 1., errors
    trial, red = generic
    weights, omega0 = state.ops.weights.astype(LD), LD(state.omega0)
    total = LD(0)
    for tile in cell_tiles(g, state.tile_size):
        jb, jt = (tile_geometry(node_field(p.u, g), state.ops, tile=tile).J for p in (base, trial))
        total += _logvol_change_sum(jb, jt, weights/(omega0*LogVolume.tau2(state, tile).astype(LD)))
        jb, jt = (tile_geometry(node_field(p.u, g), state.corner_ops, tile=tile).J for p in (base, trial))
        total += _logvol_change_sum(jb, jt, state.corner_weights.astype(LD)
                                    / (omega0*LogVolumeCorners.tau2(state, tile).astype(LD)))
    assert red.blocks["logvol"] == LD(.5)*total


