def test_corner_tau2_and_geometry():
    """tau_{K,v}^2 is the node value (= the Q1 interpolation at the corners, bitwise); the corner J are those of
    CellQ1Operators3D("corners8"), i.e. of each cell's own Q1 map (independent determinant)."""
    g, state, rng, u = corner_setup()
    tile = slice(0, g.n_cells)
    ops = CellQ1Operators3D(g, location="corners8")
    assert np.array_equal(LogVolumeCorners.tau2(state, tile), ops.interpolate(state.tau2_nodes, tile=tile))
    geo = tile_geometry(node_field(u, g), corners8(g), tile=tile)
    F = np.stack([np.stack([ops.derivative(u[..., r], axis, tile=tile) for axis in "xyz"], axis=-1)
                  for r in range(3)], axis=-2)+np.eye(3)
    assert relmax(geo.J, np.linalg.det(F)) <= 1e-14
    _, _, J = dense_corners(state, u)
    assert relmax(geo.J.ravel(), J) <= 1e-14


def test_corner_jvp_central_difference_and_adjoint(record_property):
    """C06 gates on the corner part of r_J: |(r(u + t v) - r(u - t v))/2t - K v| <= 1e-7 max(1, |K v|);
    |<K v, r> - <v, K^T r>| <= 1e-12 |K v||r|."""
    g, state, rng, u = corner_setup(seed=1)
    errors = {}
    for trial in range(3):
        v = inject_free(free_random(g, rng), g)
        v *= np.max(np.abs(u))/np.max(np.abs(v))
        t = 1e-4*np.max(np.abs(u))/np.max(np.abs(v))
        fd = (gauss_value(LogVolumeCorners, state, u+t*v)-gauss_value(LogVolumeCorners, state, u-t*v))/(2*t)
        kv = gauss_jvp(LogVolumeCorners, state, u, v)
        errors[f"jvp{trial}"] = float(np.max(np.abs(fd-kv))/max(1., np.max(np.abs(kv))))
        r = rng.normal(size=kv.shape)
        lhs, rhs = float(np.sum(kv*r)), float(theta_of(v, g)@gauss_vjp(LogVolumeCorners, state, u, r))
        errors[f"adjoint{trial}"] = abs(lhs-rhs)/(np.linalg.norm(kv)*np.linalg.norm(r))
    record_property("corner_errors", json.dumps(errors))
    assert max(v for k, v in errors.items() if k.startswith("jvp")) <= 1e-7, errors
    assert max(v for k, v in errors.items() if k.startswith("adjoint")) <= 1e-12, errors


@pytest.mark.parametrize("beta_c", [1., 2.5])
def test_dense_oracle_energy_gradient_hvp(beta_c, record_property):
    """The corner rows of an independent dense assembly: residual and Jacobian equal gauss_value / gauss_jvp of
    LogVolumeCorners (1e-12); the log-volume energy is 1/2 (|r_Gauss|^2 + |r_corners|^2), the gradient and the GN
    HVP of F_B and of the log-volume block equal sum_i K_i^T r_i and sum_i K_i^T K_i v of the dense blocks with the
    corner rows appended to r_J (1e-12); H symmetric (1e-12) and positive semidefinite."""
    g, state, rng, u = corner_setup(seed=2)
    state = state.replace(corner_weight=beta_c)
    ev = evaluate(state, u)
    dense = dense_model(state, u)
    r_c, K_c, _ = dense_corners(state, u)
    v, w = free_random(g, rng), free_random(g, rng)
    errors = dict(residual=relmax(gauss_value(LogVolumeCorners, state, u).ravel(), r_c),
                  jvp=relmax(gauss_jvp(LogVolumeCorners, state, u, v).ravel(), K_c@v))
    r_J = np.concatenate((dense["logvol"][0], r_c))
    K_J = np.concatenate((dense["logvol"][1], K_c))
    errors["logvol_energy"] = abs(ev.energies["logvol"]-.5*r_J@r_J)/(.5*r_J@r_J)
    blocks = dict(dense, logvol=(r_J, K_J))
    expected_g = sum(np.einsum("cnk,cn->k", blocks["channel"][1], blocks["channel"][0]) if name == "channel"
                     else blocks[name][1].T@blocks[name][0] for name in BLOCK_NAMES)
    expected_h = sum(np.einsum("cnk,cnj,j->k", blocks["channel"][1], blocks["channel"][1], v) if name == "channel"
                     else blocks[name][1].T@(blocks[name][1]@v) for name in BLOCK_NAMES)
    errors["gradient"] = relmax(gradient(state, ev), expected_g)
    errors["gradient_logvol"] = relmax(gradient(state, ev, blocks=("logvol",)), K_J.T@r_J)
    Hv, Hw = hvp(state, ev, v), hvp(state, ev, w)
    errors["hvp"] = relmax(Hv, expected_h)
    errors["hvp_logvol"] = relmax(hvp(state, ev, v, blocks=("logvol",)), K_J.T@(K_J@v))
    composed = gauss_vjp(LogVolume, state, u, gauss_jvp(LogVolume, state, u, v)) \
        + gauss_vjp(LogVolumeCorners, state, u, gauss_jvp(LogVolumeCorners, state, u, v))
    errors["hvp_logvol_composed"] = relmax(hvp(state, ev, v, blocks=("logvol",)), composed)
    errors["symmetry"] = abs(float(Hv@w)-float(v@Hw))/(np.linalg.norm(Hv)*np.linalg.norm(w))
    errors["blocks_sum"] = relmax(sum(gradient(state, ev, blocks=(b,)) for b in BLOCK_NAMES), gradient(state, ev))
    record_property("dense_errors", json.dumps(errors))
    assert max(errors.values()) <= 1e-12, errors
    for _ in range(5):
        x = free_random(g, rng)
        assert float(x@hvp(state, ev, x)) >= -1e-12*float(x@x)
        assert float(x@hvp(state, ev, x, blocks=("logvol",))) >= -1e-12*float(x@x)


@pytest.mark.parametrize("seed", [0, 5])
def test_energy_directional_derivative(seed, record_property):
    """C06 gate with the corners: |(F(u + t v) - F(u - t v))/2t - <grad F, v>| <= 1e-7 relative, for F_B and the
    log-volume block."""
    g, state, rng, u = corner_setup(seed=seed, student_t=bool(seed))
    v = inject_free(free_random(g, rng), g)
    v *= np.max(np.abs(u))/np.max(np.abs(v))
    t = 1e-4
    ev, plus, minus = evaluate(state, u), evaluate(state, u+t*v), evaluate(state, u-t*v)
    errors = {}
    for name, pick in (("logvol", lambda e: e.energies["logvol"]), ("F_B", lambda e: e.energy)):
        fd = (pick(plus)-pick(minus))/(2*t)
        blocks = ("logvol",) if name == "logvol" else BLOCK_NAMES
        directional = float(gradient(state, ev, blocks=blocks)@theta_of(v, g))
        errors[name] = abs(fd-directional)/abs(directional)
    record_property("directional_errors", json.dumps(errors))
    assert max(errors.values()) <= 1e-7, errors


def test_accumulation_order_threads_and_tiles():
    """C06-7 with C05-2a: the log-volume energy is float(1/2 (((G_0 + C_0) + G_1) + C_1 ...)) in longdouble, G_t and
    C_t the tile's Gauss and corner sums of r^2 (bitwise); the Gauss part alone is the default state's value
    (bitwise); cpu_threads 1, the default (4) and 8 give bitwise the same energies, gradient, HVP and stable
    comparison; another tile size changes only the rounding."""
    g, state, rng, u = corner_setup(seed=3, tile_size=7)
    ev = evaluate(state, u)
    total, gauss_only = LD(0), LD(0)
    for tile in cell_tiles(g, state.tile_size):
        rg = gauss_value(LogVolume, state, u, tile=tile)
        rc = gauss_value(LogVolumeCorners, state, u, tile=tile)
        total += np.sum(rg*rg, dtype=LD)
        total += np.sum(rc*rc, dtype=LD)
        gauss_only += np.sum(rg*rg, dtype=LD)
    assert ev.energies["logvol"] == float(LD(.5)*total)
    default = state.replace(logvol_points="gauss27")
    assert evaluate(default, u).energies["logvol"] == float(LD(.5)*gauss_only)
    assert ev.energies["logvol"] > evaluate(default, u).energies["logvol"]
    v = free_random(g, rng)
    direction = inject_free(free_random(g, rng), g)
    trial_u = u+.3*direction*np.max(np.abs(u))/np.max(np.abs(direction))
    serial = state.replace(cpu_threads=1)
    a = evaluate(serial, u)
    for threaded in (state, state.replace(cpu_threads=8)):
        b = ev if threaded is state else evaluate(threaded, u)
        assert a.total == b.total and a.energies == b.energies
        assert np.array_equal(gradient(serial, a), gradient(threaded, b))
        assert np.array_equal(hvp(serial, a, v), hvp(threaded, b, v))
        ra = stable_reduction(serial, a, evaluate(serial, trial_u))
        rb = stable_reduction(threaded, b, evaluate(threaded, trial_u))
        assert ra.delta == rb.delta and ra.blocks == rb.blocks
    big = state.replace(tile_size=8192)
    assert abs(evaluate(big, u).energies["logvol"]-ev.energies["logvol"]) <= 1e-14*ev.energies["logvol"]


