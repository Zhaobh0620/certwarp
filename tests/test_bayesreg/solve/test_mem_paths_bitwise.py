import json
from pathlib import Path

import pytest

from . import _mem_paths_digest as P
from .test_run_pair_structure import use_synthetic_folds

GOLDEN_DIR = Path(__file__).resolve().parents[1]/"_golden"
GOLDEN = GOLDEN_DIR/"golden_9747553_mem_paths.json"
GOLDEN_GF = GOLDEN_DIR/"golden_d046b77_mem_gf.json"


def _load(path):
    return json.loads(path.read_text())


def _same(digest, reference):
    """Compare two digests; on a difference name the keys and the first differing row."""
    if digest == reference:
        return
    rows = [(k, a, b) for k, (a, b) in enumerate(zip(digest.get("row_digests", []), reference.get("row_digests", [])))
            if a != b]
    keys = sorted(k for k in set(digest) | set(reference) if digest.get(k) != reference.get(k))
    raise AssertionError(f"digest differs in {keys}; first differing row {rows[:1]}")


def _check_path(name, digest):
    """The case reaches the path it is meant for (so the golden is not silently a no-fallback run)."""
    assert digest["exit_code"] == 0 and digest["status"] == "cap_reached", (name, digest["status"])
    paths = digest["paths"]
    if name.startswith("numpy"):
        assert paths["comparisons"] is None
        return
    assert paths["comparisons"] > 0
    if "fallback" in name:
        assert paths["cpu_fallback"] == paths["comparisons"] and paths["cpu_evaluations"] > 0
        assert paths["cpu_cache_hits"] > 0
    if "faults" in name:
        assert paths["device_anomalies"]["evaluate"] > 0 and paths["device_anomalies"]["compare"] > 0
        assert digest["device_anomalies"] == paths["device_anomalies"]
    if "_gf_" in name:
        assert paths["gf_rechecks"] > 0
    if not any(tag in name for tag in ("fallback", "faults", "_gf_")):
        assert paths["cpu_fallback"] == 0 and paths["gf_rechecks"] == 0


def test_golden_records_name_their_cases():
    """The golden records were made from the case table of this tree's digest module, on the stated commits, with
    the digest modules of this tree, checked by content (sha256): generator_head names the pre-rebase ids 4849144 /
    05bfda3 of the first two FUP1 commits (see the module docstring), so the commit id alone no longer locates the
    generator."""
    import hashlib
    repo = Path(__file__).resolve().parents[3]
    for path, case_set, ref in ((GOLDEN, "golden", "9747553"), (GOLDEN_GF, "gf", "d046b77")):
        record = _load(path)
        assert record["case_set"] == case_set and record["ref"] == ref and record["ref_commit"].startswith(ref)
        assert not record["generator_dirty"]
        assert record["digest_modules"] == {rel: hashlib.sha256((repo/rel).read_bytes()).hexdigest()
                                            for rel in ("tests/test_bayesreg/solve/_mem_digest.py",
                                                        "tests/test_bayesreg/solve/_mem_paths_digest.py")}
        cases = {name: dict(backend=b, options=list(o), patches=list(p))
                 for name, (b, o, p) in P.CASE_SETS[case_set].items()}
        assert record["cases"] == cases and set(record["digests"]) == set(cases)


@pytest.mark.parametrize("name", sorted(P.GOLDEN_CASES))
def test_paths_are_bitwise_the_code_before_mem(name, monkeypatch):
    use_synthetic_folds(monkeypatch)                                            # C23.9-13 (8), revision 6f: the synthetic training draw; the golden is not changed
    backend = P.GOLDEN_CASES[name][0]
    if backend == "torch64":
        pytest.importorskip("torch")
    golden = _load(GOLDEN)["digests"][name]
    _check_path(name, golden)
    digest = P.case_digest(name)
    _check_path(name, digest)
    _same(digest, golden)


@pytest.mark.parametrize("name", sorted(P.GF_CASES))
def test_gf_recheck_paths_regression(name, monkeypatch):
    """Regression only: the current code against digests of the current code (d046b77).  NOT a proof of bitwise
    equality with the code before MEM -- on 9747553 these runs ended with TypeError in run_pg (the GFR bug)."""
    use_synthetic_folds(monkeypatch)                                            # C23.9-13 (8), revision 6f: the synthetic training draw; the golden is not changed
    pytest.importorskip("torch")
    golden = _load(GOLDEN_GF)["digests"][name]
    _check_path(name, golden)
    digest = P.case_digest(name)
    _check_path(name, digest)
    _same(digest, golden)


def test_patches_are_restored():
    pytest.importorskip("torch")
    import bayesreg.backends.torch64 as T
    from bayesreg.backends.torch64 import stable
    before = (stable.BAND_FACTOR, stable.GF_BAND, T.evaluate)
    with P.patched(("band", "faults", "gf")):
        assert stable.BAND_FACTOR == 1e300 and stable.GF_BAND == 1e30 and T.evaluate is not before[2]
    assert (stable.BAND_FACTOR, stable.GF_BAND, T.evaluate) == before
    with pytest.raises(ValueError):
        with P.patched(("unknown",)):
            pass
